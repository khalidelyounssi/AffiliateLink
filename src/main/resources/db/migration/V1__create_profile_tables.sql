CREATE TABLE profile_profiles (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  email VARCHAR(254) NOT NULL,
                                  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                                  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                                  CONSTRAINT uk_profile_email UNIQUE (email),
                                  CONSTRAINT ck_profile_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED'))
);

CREATE TABLE profile_publishers (
                                    id BIGINT PRIMARY KEY REFERENCES profile_profiles(id),
                                    first_name VARCHAR(100) NOT NULL,
                                    last_name VARCHAR(100) NOT NULL,
                                    niche VARCHAR(20) NOT NULL,
                                    bio VARCHAR(1000),
                                    country VARCHAR(100) NOT NULL,
                                    CONSTRAINT ck_publisher_niche CHECK (
                                        niche IN ('BEAUTY', 'TECH', 'GAMING', 'TRAVEL', 'LIFESTYLE', 'FOOD', 'SPORT')
                                        )
);

CREATE TABLE profile_advertisers (
                                     id BIGINT PRIMARY KEY REFERENCES profile_profiles(id),
                                     company_name VARCHAR(200) NOT NULL,
                                     sector VARCHAR(100) NOT NULL,
                                     website VARCHAR(500) NOT NULL
);