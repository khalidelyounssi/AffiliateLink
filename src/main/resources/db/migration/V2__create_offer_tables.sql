CREATE TABLE offer_offres (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              advertiser_id BIGINT NOT NULL,
                              title VARCHAR(200) NOT NULL,
                              description VARCHAR(4000) NOT NULL,
                              landing_url VARCHAR(1000) NOT NULL,
                              niche VARCHAR(20) NOT NULL CHECK (niche IN ('BEAUTY','TECH','GAMING','TRAVEL','LIFESTYLE','FOOD','SPORT')),
                              created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_offer_advertiser ON offer_offres(advertiser_id);
CREATE TABLE offer_tags (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(50) NOT NULL,
                            CONSTRAINT uk_offer_tag_name UNIQUE(name),
                            CONSTRAINT ck_offer_tag_lower CHECK (name = lower(trim(name)) AND length(name) > 0)
);
CREATE TABLE offer_offre_tags (
                                  offre_id BIGINT NOT NULL REFERENCES offer_offres(id),
                                  tag_id BIGINT NOT NULL REFERENCES offer_tags(id),
                                  PRIMARY KEY (offre_id, tag_id)
);
CREATE TABLE offer_campaigns (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 offre_id BIGINT NOT NULL REFERENCES offer_offres(id),
                                 name VARCHAR(200) NOT NULL,
                                 start_date DATE NOT NULL,
                                 end_date DATE NOT NULL,
                                 budget NUMERIC(19,2) NOT NULL CHECK (budget > 0),
                                 payout_model VARCHAR(20) NOT NULL CHECK (payout_model IN ('CPC','CPL','CPA_FIXED','CPA_PERCENT')),
                                 payout_value NUMERIC(19,4) NOT NULL,
                                 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','ACTIVE','PAUSED','ENDED')),
                                 CONSTRAINT ck_campaign_dates CHECK (end_date > start_date),
                                 CONSTRAINT ck_campaign_payout CHECK (
                                     (payout_model = 'CPA_PERCENT' AND payout_value >= 0 AND payout_value <= 100)
                                         OR (payout_model <> 'CPA_PERCENT' AND payout_value > 0)
                                     )
);
CREATE INDEX ix_campaign_offre ON offer_campaigns(offre_id);
CREATE UNIQUE INDEX uk_one_active_campaign_per_offre ON offer_campaigns(offre_id) WHERE status = 'ACTIVE';
